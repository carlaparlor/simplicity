"""Deterministic grayscale 's' icon, stdlib-only. Regenerate, never hand-edit outputs."""
from pathlib import Path
import math
import struct
import zlib

ROOT = Path(__file__).resolve().parents[2]
SIZES = (16, 24, 32, 48, 64, 128, 256)
# A compact lowercase s, as a filled outline; coordinates in a 100-unit square.
CURVES = (
    ((70, 32), (61, 25), (33, 25), (29, 41)),
    ((29, 41), (24, 62), (61, 53), (60, 64)),
    ((60, 64), (59, 74), (40, 72), (30, 65)),
    ((30, 65), (28, 69), (26, 73), (25, 76)),
    ((25, 76), (38, 85), (68, 86), (73, 67)),
    ((73, 67), (79, 45), (42, 53), (42, 42)),
    ((42, 42), (43, 32), (58, 36), (65, 41)),
    ((65, 41), (67, 38), (69, 34), (70, 32)),
)


def outline():
    points = []
    for a, b, c, d in CURVES:
        for step in range(16):
            t = step / 16
            points.append(tuple((1-t)**3*a[i] + 3*(1-t)**2*t*b[i] + 3*(1-t)*t*t*c[i] + t**3*d[i] for i in (0, 1)))
    return points


def chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def png(size):
    scale = 4
    n = size * scale
    mask = bytearray(n*n)
    points = [(x*n/100, y*n/100) for x, y in outline()]
    edges = list(zip(points, points[1:] + points[:1]))
    for y in range(n):
        yy = y + 0.5
        xs = sorted(a[0] + (yy-a[1])*(b[0]-a[0])/(b[1]-a[1]) for a, b in edges if (a[1] > yy) != (b[1] > yy))
        for left, right in zip(xs[::2], xs[1::2]):
            lo, hi = max(0, math.ceil(left-0.5)), min(n, math.ceil(right-0.5))
            mask[y*n+lo:y*n+hi] = b'\1' * (hi-lo)
    rows = bytearray()
    radius = n * 0.075
    for y in range(size):
        rows.append(0)  # PNG filter None, easy to audit in tests.
        for x in range(size):
            alpha = value = 0
            for dy in range(scale):
                for dx in range(scale):
                    xx, yy = x*scale+dx+0.5, y*scale+dy+0.5
                    cx, cy = min(max(xx, radius), n-radius), min(max(yy, radius), n-radius)
                    inside = (xx-cx)**2+(yy-cy)**2 <= radius**2
                    alpha += 255 if inside else 0
                    value += 238 if mask[int(yy)*n+int(xx)] else 91
            grey = round(value / (scale*scale))
            rows.extend((grey, grey, grey, round(alpha / (scale*scale))))
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(rows, 9)) + chunk(b'IEND', b'')


def generate(root):
    images = [png(size) for size in SIZES]
    offset = 6 + 16*len(images)
    entries = []
    for size, data in zip(SIZES, images):
        entries.append(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(data), offset))
        offset += len(data)
    icon = struct.pack('<HHH', 0, 1, len(images)) + b''.join(entries) + b''.join(images)
    target = root / 'app/assets/simplicity.ico'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(icon)
    header = root / 'modules/gui/include/simplicity/application_icon.h'
    header.parent.mkdir(parents=True, exist_ok=True)
    lines = [', '.join(f'0x{b:02x}' for b in images[-1][i:i+16]) for i in range(0, len(images[-1]), 16)]
    header.write_bytes(('// Generated by tools/assets/make_app_icon.py.\n#pragma once\nnamespace simplicity {\ninline constexpr unsigned char applicationIconPng[] = {\n    ' + ',\n    '.join(lines) + '\n};\n}\n').encode('utf-8'))


if __name__ == '__main__':
    generate(ROOT)
