"""Embed exact vendored Lucide SVGs and RetroByte bytes; no runtime files/network."""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
LUCIDE_COMMIT = 'c29c276f16590cf017126671535ad8c792be64d8'
ICONS = ['play', 'pause', 'square', 'circle', 'repeat-2', 'undo-2', 'redo-2',
         'folder', 'panels-top-left', 'grid-2x2', 'sliders-horizontal',
         'circle-question-mark', 'plus', 'minus', 'search', 'copy', 'trash',
         'file', 'audio-lines', 'list-music', 'waves-horizontal', 'drum', 'arrow-right',
         'volume-2', 'chevron-down', 'x', 'minimize', 'maximize']


def generate(root):
    assets = ROOT / 'modules/gui/assets'
    output = root / 'modules/gui/include/simplicity/ui_asset_data.h'
    output.parent.mkdir(parents=True, exist_ok=True)
    font = (assets / 'retrobyte/RetroByte.ttf').read_bytes()
    lines = ['// Generated by tools/assets/make_ui_assets.py; see assets/* notices.',
             '#pragma once', 'namespace simplicity::ui::data {',
             'inline constexpr unsigned char retrobyte[] = {']
    lines.extend('    ' + ', '.join(f'0x{b:02x}' for b in font[i:i+16]) + ',' for i in range(0,len(font),16))
    lines.extend(['};', 'inline constexpr const char* lucide[] = {'])
    for name in ICONS:
        svg = (assets / f'lucide/{name}.svg').read_text().strip()
        lines.append('R"lucide(' + svg + ')lucide",')
    lines.extend(['};', '}'])
    output.write_bytes(('\n'.join(lines)+'\n').encode())
    manifest = {'lucide_commit': LUCIDE_COMMIT, 'font_sha256': hashlib.sha256(font).hexdigest(),
                'icons': {n: hashlib.sha256((assets / f'lucide/{n}.svg').read_bytes()).hexdigest() for n in ICONS}}
    path = root / 'modules/gui/assets/manifest.json'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(manifest, indent=2)+'\n').encode())


if __name__ == '__main__':
    generate(ROOT)
